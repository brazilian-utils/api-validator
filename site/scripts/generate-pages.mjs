#!/usr/bin/env node
/**
 * Generates, for each language:
 *   src/content/docs/[pt-br/]utils/<slug>.mdx   one page per contract domain (../contract/<domain>.json)
 *   src/content/docs/[pt-br/]libs/<lib>.mdx     one status page per library (../libs/<lib>.json)
 *
 * A utility page: header (summary, per-library availability) → the long-form spec when the
 * domain has one → one section per operation (signature, status per library, the contract's
 * description, a usage tab per library, the shared test cases) → official sources.
 *
 * The pages are regenerated on every build and ignored by git: adding a function or a domain to
 * the contract adds it to the site, adding a library to libs/ adds its tab and status page.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { DOCS_DIR, LANGS, LANG_PREFIX, loadGuide, loadGuides, loadLibs, loadSpecs, loadUsageManifest } from '../src/lib/registry.mjs';
import { signature } from '../src/lib/text.mjs';

const HEADINGS = {
  en: { operations: 'Usage', references: 'Official sources', libTitle: (l) => `${l} status`, conventions: 'API conventions' },
  'pt-BR': { operations: 'Uso', references: 'Fontes oficiais', libTitle: (l) => `Situação: ${l}`, conventions: 'Convenções da API' },
};
const LIB_DESCRIPTION = {
  en: (l) => `How the ${l} library stands against the shared contract: what it implements, what fails and what to do next.`,
  'pt-BR': (l) => `Como a biblioteca ${l} está em relação ao contrato: o que implementa, o que falha e o que fazer agora.`,
};
const EDIT_BASE = 'https://github.com/brazilian-utils/api-validator/edit/main/';

const specs = loadSpecs();
const libs = loadLibs();
const guides = loadGuides();
const usageManifest = loadUsageManifest();

for (const lang of LANGS) {
  const root = path.join(DOCS_DIR, LANG_PREFIX[lang]);
  for (const [dir, items, render] of [
    ['utils', specs, (s) => [s.id, utilPage(s, lang)]],
    ['libs', libs, (l) => [l.id, libPage(l, lang)]],
    ['guides', guides, (g) => [`${g.lib}/${g.slug}`, guidePage(g, lang)]],
  ]) {
    const out = path.join(root, dir);
    await fs.rm(out, { recursive: true, force: true });
    await fs.mkdir(out, { recursive: true });
    for (const item of items) {
      const [name, content] = render(item);
      await fs.mkdir(path.dirname(path.join(out, name)), { recursive: true });
      await fs.writeFile(path.join(out, `${name}.mdx`), content, 'utf8');
    }
  }
}

console.log(`pages  generated ${specs.length} utilities, ${libs.length} library pages and ${guides.length} guides × ${LANGS.length} languages`);

function utilPage(spec, lang) {
  const h = HEADINGS[lang];
  const ops = spec.operations
    .map((op) => {
      const notes = op.network || op.deprecated;
      return [
        `### ${mdxText(op.label[lang])}`,
        '',
        '```txt',
        signature(op),
        '```',
        '',
        `<OpStatus fn="${op.fnId}" />`,
        '',
        op.description ? mdx(op.description) : op.summary ? mdx(op.summary) : '',
        notes ? `\n<OpNotes network={${op.network}} deprecated={${op.deprecated}} />` : '',
        '',
        `<Usage util="${spec.id}" op="${op.id}" fn="${op.fnId}" />`,
        '',
        `<TryIt util="${spec.id}" op="${op.id}" />`,
        '',
        `<Cases util="${spec.id}" op="${op.id}" />`,
        '',
      ].join('\n');
    })
    .join('\n');
  return `---
# Generated by site/scripts/generate-pages.mjs from contract/${spec.domain}.json. Do not edit.
title: ${JSON.stringify(spec.title[lang])}
description: ${JSON.stringify(spec.summary[lang] ?? '')}
editUrl: ${EDIT_BASE}contract/${spec.domain}.json
---
import UtilHeader from '@components/UtilHeader.astro';
import SpecBody from '@components/SpecBody.astro';
import References from '@components/References.astro';
import Usage from '@components/Usage.astro';
import Cases from '@components/Cases.astro';
import OpStatus from '@components/OpStatus.astro';
import OpNotes from '@components/OpNotes.astro';
import OpsIntro from '@components/OpsIntro.astro';
import TryIt from '@components/TryIt.astro';

<UtilHeader util="${spec.id}" />

<SpecBody util="${spec.id}" />

## ${h.operations}

<OpsIntro />

${ops}
## ${h.references}

<References util="${spec.id}" />
`;
}

function libPage(lib, lang) {
  // The intro of the library's reference page (rules every function follows), when it has one.
  const intro = usageManifest?.libs?.[lib.id]?.intro ?? {};
  const text = intro[lang] ?? intro.en;
  const conventions = text ? `\n## ${HEADINGS[lang].conventions}\n\n${mdx(demote(text))}\n` : '';
  return `---
# Generated by site/scripts/generate-pages.mjs from libs/brazilian-utils-${lib.id}.json and the last api-validator run. Do not edit.
title: ${JSON.stringify(HEADINGS[lang].libTitle(lib.label))}
description: ${JSON.stringify(LIB_DESCRIPTION[lang](lib.label))}
editUrl: false
---
import LibStatus from '@components/LibStatus.astro';

<LibStatus lib="${lib.id}" />
${conventions}`;
}

/** Headings of embedded Markdown one level down, so they nest under the page's own. */
function demote(markdown) {
  let inFence = false;
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
      return !inFence && /^#{1,5}\s/.test(line) ? `#${line}` : line;
    })
    .join('\n');
}

/**
 * A library guide: its prose, and each group of examples as tabs (framework → variant → file),
 * with the live demo above the files. Framework and variant tabs are synced across the site, so a
 * React reader stays on React from guide to guide.
 */
function guidePage(entry, lang) {
  const guide = loadGuide(entry.lib, entry.slug, lang);
  const lib = libs.find((l) => l.id === entry.lib);
  const body = guide.blocks.map((b) => (b.type === 'markdown' ? mdx(b.text) : examples(b.examples))).join('\n\n');
  return `---
# Generated by site/scripts/generate-pages.mjs from ${entry.source}. Do not edit.
title: ${JSON.stringify(guide.title)}
description: ${JSON.stringify(guide.description ?? '')}
editUrl: ${JSON.stringify(entry.source.replace('/blob/', '/edit/'))}
---
import { Tabs, TabItem } from '@astrojs/starlight/components';
import GuideHeader from '@components/GuideHeader.astro';
import LiveDemo from '@components/LiveDemo.astro';

<GuideHeader lib="${lib.id}" slug="${entry.slug}" shown="${guide.locale}" />

${body}
`;
}

function examples(list) {
  const tabs = (key, items, render) =>
    [`<Tabs${key ? ` syncKey="${key}"` : ''}>`, ...items.map((it) => `<TabItem label=${JSON.stringify(it.name ?? '')}>\n\n${render(it)}\n\n</TabItem>`), '</Tabs>'].join('\n');
  const files = (node) => {
    const list = node.children.filter((c) => c.kind === 'file');
    const blocks = list.map((f) => fence(f.code, f.lang, list.length === 1 ? f.name : undefined));
    return list.length > 1 ? tabs(null, list, (f) => fence(f.code, f.lang)) : blocks.join('\n');
  };
  const content = (node) => {
    const parts = [];
    if (node.intro) parts.push(mdx(node.intro));
    const variants = node.children.filter((c) => c.kind === 'variant');
    if (variants.length) parts.push(tabs('guide-variant', variants, content));
    else {
      if (node.demo) parts.push(`<LiveDemo src=${JSON.stringify(node.demo)} title=${JSON.stringify(node.name ?? '')} />`);
      if (node.children.length) parts.push(files(node));
    }
    return parts.join('\n\n');
  };
  return tabs('guide-example', list, content);
}

/** A fenced code block that survives any backticks in the code. */
function fence(code, lang, title) {
  const longest = Math.max(2, ...[...String(code).matchAll(/`+/g)].map((m) => m[0].length));
  const marks = '`'.repeat(longest + 1);
  return `${marks}${lang ?? ''}${title ? ` title=${JSON.stringify(title)}` : ''}\n${String(code).replace(/\n$/, '')}\n${marks}`;
}

/**
 * Contract markdown into MDX: `{`, `}` and `<` mean JSX in MDX, so outside code spans and code
 * blocks they are escaped.
 */
function mdx(markdown) {
  let inFence = false;
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : mdxText(part)))
        .join('');
    })
    .join('\n');
}

function mdxText(text) {
  return String(text).replace(/[{}<>]/g, (c) => ({ '{': '&#123;', '}': '&#125;', '<': '&lt;', '>': '&gt;' })[c]);
}
