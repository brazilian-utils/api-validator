#!/usr/bin/env node
/**
 * Generates one page per spec and per language:
 *   src/content/docs/utils/<id>.mdx          (en)
 *   src/content/docs/pt-br/utils/<id>.mdx    (pt-BR)
 *
 * The pages are thin: title/description from meta.yaml plus the shared components.
 * They are regenerated on every build and ignored by git, so adding a utility to the site
 * means adding `specs/<id>/` with a `meta.yaml`, nothing else.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { DOCS_DIR, LANGS, LANG_PREFIX, loadSpecs } from '../src/lib/registry.mjs';

const HEADINGS = {
  en: { rules: 'Rules and algorithm', references: 'Official sources', usage: 'Usage', tests: 'Test cases' },
  'pt-BR': { rules: 'Regras e algoritmo', references: 'Fontes oficiais', usage: 'Uso', tests: 'Casos de teste' },
};

const specs = loadSpecs();

for (const lang of LANGS) {
  const dir = path.join(DOCS_DIR, LANG_PREFIX[lang], 'utils');
  await fs.rm(dir, { recursive: true, force: true });
  await fs.mkdir(dir, { recursive: true });
  for (const spec of specs) {
    await fs.writeFile(path.join(dir, `${spec.id}.mdx`), page(spec, lang), 'utf8');
  }
}

console.log(`pages  generated ${specs.length} utilit${specs.length === 1 ? 'y' : 'ies'} × ${LANGS.length} languages`);

function page(spec, lang) {
  const h = HEADINGS[lang];
  const title = yamlString(spec.title[lang]);
  const description = yamlString(spec.summary[lang]);
  return `---
# Generated by scripts/generate-pages.mjs from specs/${spec.id}/meta.yaml. Do not edit.
title: ${title}
description: ${description}
editUrl: https://github.com/brazilian-utils/api-validator/edit/main/site/specs/${spec.id}/${lang === 'pt-BR' ? 'spec.md' : 'spec_en.md'}
---
import UtilHeader from '@components/UtilHeader.astro';
import SpecBody from '@components/SpecBody.astro';
import References from '@components/References.astro';
import Usage from '@components/Usage.astro';
import TestCases from '@components/TestCases.astro';

<UtilHeader util="${spec.id}" />

<SpecBody util="${spec.id}" />

## ${h.references}

<References util="${spec.id}" />

## ${h.usage}

<Usage util="${spec.id}" />

## ${h.tests}

<TestCases util="${spec.id}" />
`;
}

function yamlString(value) {
  return JSON.stringify(String(value ?? ''));
}
